LEFT JOIN RORSAPR K
ON          RPRAWRD_PIDM = K.RORSAPR_PIDM
AND         K.RORSAPR_TERM_CODE = :FAL_PRD

LEFT JOIN RORSAPR L
ON          RPRAWRD_PIDM = L.RORSAPR_PIDM
AND         L.RORSAPR_TERM_CODE = :SPR_PRD

LEFT JOIN SGBSTDN
ON          RPRAWRD_PIDM = SGBSTDN_PIDM

LEFT JOIN RWBPLAP
ON          RPRAWRD_PIDM = RWBPLAP_PIDM
AND         RPRAWRD_AIDY_CODE = RWBPLAP_AIDY_CODE
AND         RPRAWRD_FUND_CODE = RWBPLAP_FUND_CODE

LEFT JOIN RORSTAT
ON          RORSTAT_PIDM = RPRAWRD_PIDM
AND         RORSTAT_AIDY_CODE = RPRAWRD_AIDY_CODE

where rprawrd_aidy_code = :AIDY
and     RWBPLAP_fund_code not like '_____X'
and     rprawrd_accept_amt > 0
AND     SGBSTDN_TERM_CODE_EFF =
        (SELECT MAX(SGBSTDN_TERM_CODE_EFF)
        FROM SGBSTDN_AUDIT G
        WHERE G.SGBSTDN_PIDM = RPRAWRD_PIDM
        AND G.SGBSTDN_TERM_CODE_EFF <= :SPR_PRD)

