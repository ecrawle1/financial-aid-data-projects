ON          G.RRRAREQ_PIDM = RPRAWRD_PIDM
AND         G.RRRAREQ_AIDY_CODE = :AIDY
AND         G.RRRAREQ_TREQ_CODE = 'NSLDSA'

LEFT JOIN RRRAREQ H
ON          H.RRRAREQ_PIDM = RPRAWRD_PIDM
AND         H.RRRAREQ_AIDY_CODE = :AIDY
AND         H.RRRAREQ_TREQ_CODE = 'NSLDSR'

